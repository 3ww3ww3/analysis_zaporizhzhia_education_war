SELECT 
    "Територіальний розріз",
    "Показник",
    "Категорія розрізу",
    "Розріз",
    Рік,
    CASE Рік
        WHEN '2019' THEN "2019"
        WHEN '2020' THEN "2020"
        WHEN '2021' THEN "2021"
        WHEN '2022' THEN "2022"
        WHEN '2023' THEN "2023"
        WHEN '2024' THEN "2024"
        WHEN '2025' THEN "2025"
    END AS "Значення"
FROM dataset
JOIN (
    SELECT '2019' AS Рік UNION ALL
    SELECT '2020' AS Рік UNION ALL
    SELECT '2021' AS Рік UNION ALL
    SELECT '2022' AS Рік UNION ALL
    SELECT '2023' AS Рік UNION ALL
    SELECT '2024' AS Рік UNION ALL
    SELECT '2025' AS Рік
)
WHERE "Територіальний розріз" IN ('Запорізька', 'Україна')
  AND (
      ("Показник" = 'Кількість учнів у закладах загальної середньої освіти'
       AND (
           ("Категорія розрізу" = 'Усього' AND "Тип місцевості" = 'Загалом')
           OR ("Категорія розрізу" = 'Класи' AND "Розріз" IN ('1 клас', '5 клас', '9 клас', '11 клас'))
       )
      )
      OR ("Показник" = 'Кількість закладів загальної середньої освіти' AND "Категорія розрізу" = 'Усього' AND "Тип місцевості" = 'Загалом')
      OR ("Показник" = 'Кількість вчителів у закладах загальної середньої освіти' AND "Категорія розрізу" = 'Усього')
  )
ORDER BY "Показник", "Розріз", "Територіальний розріз", Рік;